import { readdirSync, writeFileSync, existsSync } from "node:fs";
import { extname, basename, join } from "node:path";

const fontsDir = join(process.cwd(), "public", "fonts");
const outputFile = join(process.cwd(), "app", "generated-fonts.css");
const fontExtensions = new Set([".ttf", ".otf", ".woff", ".woff2"]);
const ignoredFontFiles = new Set(["ZaoZiGongFangYuanHeiTi-2.ttf"]);

const aliasMap = {
  "PingFang-SC-Bold.ttf": [
    { family: "PingFangSCMedium", weight: 500 },
    { family: "PingFang SC", weight: 500 },
  ],
  "PingFangSC-Medium.ttf": [
    { family: "PingFangSCMedium", weight: 500 },
    { family: "PingFang SC", weight: 500 },
  ],
  "PingFang-SC-Medium.ttf": [
    { family: "PingFangSCMedium", weight: 500 },
    { family: "PingFang SC", weight: 500 },
  ],
  "PingFangSC-Medium.otf": [
    { family: "PingFangSCMedium", weight: 500 },
    { family: "PingFang SC", weight: 500 },
  ],
  "PingFang-SC-Medium.otf": [
    { family: "PingFangSCMedium", weight: 500 },
    { family: "PingFang SC", weight: 500 },
  ],
  "FliggyFont-Medium.ttf": [
    { family: "FliggyFontMedium", weight: 500 },
    { family: "FliggyFont", weight: 500 },
  ],
  "FliggySans102-Md.ttf": [
    { family: "FliggySans102Medium", weight: 500 },
    { family: "Fliggy Sans 102", weight: 500 },
  ],
  "FliggySans102-Rg.ttf": [
    { family: "FliggySans102Regular", weight: 400 },
  ],
};

function cssString(value) {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

function familyFromFile(file) {
  return basename(file, extname(file)).replace(/[^a-zA-Z0-9]+/g, "");
}

if (!existsSync(fontsDir)) {
  writeFileSync(outputFile, "/* No fonts found. */\n");
  process.exit(0);
}

const fontFiles = readdirSync(fontsDir)
  .filter((file) => fontExtensions.has(extname(file).toLowerCase()))
  .filter((file) => !file.startsWith("._"))
  .filter((file) => !ignoredFontFiles.has(file))
  .sort();

const blocks = [
  "/* Auto-generated by scripts/generate-font-css.mjs. */",
  "/* It scans public/fonts and emits local @font-face rules for deployment parity. */",
];

for (const file of fontFiles) {
  const aliases = aliasMap[file] ?? [{ family: familyFromFile(file), weight: 400 }];

  for (const alias of aliases) {
    blocks.push(
      [
        "@font-face {",
        `  font-family: "${cssString(alias.family)}";`,
        `  src: url("/fonts/${cssString(file)}") format("truetype");`,
        `  font-weight: ${alias.weight};`,
        "  font-style: normal;",
        "  font-display: swap;",
        "}",
      ].join("\n"),
    );
  }
}

writeFileSync(outputFile, `${blocks.join("\n\n")}\n`);
